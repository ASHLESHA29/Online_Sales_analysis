# monthly analysis
SELECT MONTHNAME(DATE) AS MON FROM SALES;
SELECT 
    MONTHNAME(`DATE`) AS months,
    COUNT(*) AS mon_sales
FROM sales
GROUP BY MONTHNAME(`DATE`);

SELECT                                                           # months having max sales
    MONTHNAME(`DATE`) AS month,
    COUNT(*) AS mon_sales
FROM sales
GROUP BY MONTHNAME(`DATE`)
ORDER BY mon_sales DESC
LIMIT 3;

SELECT                                                           # months having min sales
    MONTHNAME(`DATE`) AS month,
    COUNT(*) AS mon_sales
FROM sales
GROUP BY MONTHNAME(`DATE`)
ORDER BY mon_sales ASC
LIMIT 2;




## finding top 10 products which sold max
SELECT SUM(`UNITS SOLD`) FROM SALES;

SELECT `PRODUCT NAME`, SUM(`UNITS SOLD`) AS UNIT FROM SALES
GROUP BY `PRODUCT NAME`
ORDER BY UNIT DESC
LIMIT 10;



## TOP 10 products that generate max revenue
SELECT `PRODUCT NAME`, SUM(`TOTAL REVENUE`) AS TOTAL FROM SALES
GROUP BY `PRODUCT NAME`
ORDER BY TOTAL DESC
LIMIT 10;




