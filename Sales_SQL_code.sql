# duplicate value
SELECT 'TRANSACTION ID', COUNT(*) AS ID FROM sales
GROUP BY 'TRANSACTION ID'
HAVING COUNT(*) > 1;



# rounding of price
SELECT CEILING(`UNIT PRICE`) AS 'ITEM PRICE' FROM SALES;
SELECT CEILING(`TOTAL REVENUE`) AS TOTAL_REVENUE FROM sales;

UPDATE sales A
JOIN ( SELECT `TRANSACTION ID`, CEILING(`UNIT PRICE`) AS ITEM_PRICE 
	   FROM SALES
       ) B
ON A.`TRANSACTION ID` = B.`TRANSACTION ID`
SET A.`UNIT PRICE` = B.ITEM_PRICE;

UPDATE sales A
JOIN ( SELECT `TRANSACTION ID`, CEILING(`TOTAL REVENUE`) AS PRICE 
	   FROM SALES
       ) B
ON A.`TRANSACTION ID` = B.`TRANSACTION ID`
SET A.`TOTAL REVENUE` = B.PRICE;

